package application;

import java.sql.Connection;
import java.sql.Date;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;

/**
 * All database (JDBC) code for the patients table.
 * Every method opens its own Connection with try-with-resources,
 * so the Connection, PreparedStatement and ResultSet are always closed.
 * Errors are thrown as SQLException so the user interface can show them.
 */
public class PatientDAO {

    // Change these to match your own MySQL installation
    private static final String DB_URL = "jdbc:mysql://localhost:3306/hospital_db";
    private static final String DB_USER = "root";
    private static final String DB_PASSWORD = "Judegerry@1705";

    private static final String SELECT_COLUMNS =
            "SELECT patient_id, name, age, gender, phone, diagnosis, admission_date "
            + "FROM patients ";

    private Connection getConnection() throws SQLException {
        return DriverManager.getConnection(DB_URL, DB_USER, DB_PASSWORD);
    }

    // CREATE - insert a new patient (patient_id is generated by MySQL)
    public int addPatient(Patient patient) throws SQLException {

        String sql = "INSERT INTO patients "
                + "(name, age, gender, phone, diagnosis, admission_date) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, patient.getName());
            statement.setInt(2, patient.getAge());
            statement.setString(3, patient.getGender());
            statement.setString(4, patient.getPhone());
            statement.setString(5, patient.getDiagnosis());
            statement.setDate(6, Date.valueOf(patient.getAdmissionDate()));

            return statement.executeUpdate();
        }
    }

    // READ - get every patient
    public List<Patient> getAllPatients() throws SQLException {

        String sql = SELECT_COLUMNS + "ORDER BY patient_id";
        List<Patient> patients = new ArrayList<>();

        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {

            while (resultSet.next()) {
                patients.add(createPatient(resultSet));
            }
        }
        return patients;
    }

    // SEARCH - find patients by name or phone with a parameterized LIKE query
    public List<Patient> searchPatients(String keyword) throws SQLException {

        String sql = SELECT_COLUMNS
                + "WHERE name LIKE ? OR phone LIKE ? ORDER BY patient_id";
        List<Patient> patients = new ArrayList<>();

        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            String pattern = "%" + keyword + "%";
            statement.setString(1, pattern);
            statement.setString(2, pattern);

            try (ResultSet resultSet = statement.executeQuery()) {
                while (resultSet.next()) {
                    patients.add(createPatient(resultSet));
                }
            }
        }
        return patients;
    }

    // UPDATE - change the patient with the selected patient_id
    public int updatePatient(Patient patient) throws SQLException {

        String sql = "UPDATE patients SET name = ?, age = ?, gender = ?, "
                + "phone = ?, diagnosis = ?, admission_date = ? "
                + "WHERE patient_id = ?";

        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, patient.getName());
            statement.setInt(2, patient.getAge());
            statement.setString(3, patient.getGender());
            statement.setString(4, patient.getPhone());
            statement.setString(5, patient.getDiagnosis());
            statement.setDate(6, Date.valueOf(patient.getAdmissionDate()));
            statement.setInt(7, patient.getPatientId());

            return statement.executeUpdate();
        }
    }

    // DELETE - remove the patient with the selected patient_id
    public int deletePatient(int patientId) throws SQLException {

        String sql = "DELETE FROM patients WHERE patient_id = ?";

        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setInt(1, patientId);
            return statement.executeUpdate();
        }
    }

    // Turns the current ResultSet row into a Patient object
    private Patient createPatient(ResultSet resultSet) throws SQLException {

        return new Patient(
                resultSet.getInt("patient_id"),
                resultSet.getString("name"),
                resultSet.getInt("age"),
                resultSet.getString("gender"),
                resultSet.getString("phone"),
                resultSet.getString("diagnosis"),
                resultSet.getDate("admission_date").toLocalDate());
    }
}
